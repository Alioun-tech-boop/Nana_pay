function order(
  id: string,
  reference: string,
  merchantId: string,
  merchantName: string,
  productId: string,
  productName: string,
  amount: number,
  financingMode: 'SAVINGS' | 'VAULT' | 'CREDIT',
  financingId: string | null,
  financingStatus: string,
  financingAmount: number,
  status: Order['status'],
  createdInDays: number,
  updatedInDays: number,
): Order {
  return {
    id,
    reference,
    client: { id: mockUser.id, fullName: mockUser.fullName },
    merchant: { id: merchantId, name: merchantName },
    product: { id: productId, name: productName, price: { amount, currency: XOF } },
    financingMode,
    financing:
      financingId === null
        ? null
        : { id: financingId, status: financingStatus, amount: { amount: financingAmount, currency: XOF } },
    status,
    payment: null,
    createdAt: daysAgo(createdInDays),
    updatedAt: secondsAgo(Math.max(1, updatedInDays === 0 ? 3600 : updatedInDays * 86_400)),
  }
}

